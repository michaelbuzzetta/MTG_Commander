import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');

// Step 1 inventory targets the mutable parts of authoritative game state named in
// the workflow: life, tapped status, counters, zone containers, commander state,
// turn/priority state, combat state, and related player/object fields.
const PROPERTY_ASSIGNMENT = /\.(?:life|tapped|counters|damageMarked|controller|owner|zone|attacking|blocking|lost|winner|priorityPlayer|activePlayer|phase|phaseIndex|passes|pendingChoice|turn|turnActionPending|gameBegun|started|summoningSick|commanderDamage|commanderCastCount|manaPool|landPlaysThisTurn|cardsDrawnThisTurn|currentDefender|attackers|attackTargets|blockers)\b(?:\s*\[[^\]]+\]){0,3}\s*(?:\+\+|--|\+=|-=|(?<![=!<>])=(?!=))/;
const INDEXED_ASSIGNMENT = /\.(?:counters|commanderDamage|commanderCastCount|manaPool|cardsDrawnThisTurn|attackTargets|blockers)\s*\[[^\]]+\](?:\s*\[[^\]]+\]){0,2}\s*(?:\+\+|--|\+=|-=|(?<![=!<>])=(?!=))/;
const ZONE_MUTATOR = /\.(?:hand|library|battlefield|graveyard|exile|command|stack|history|pendingTriggers)\b[^;\n]*?\.(?:push|pop|shift|unshift|splice|sort|reverse)\s*\(/;
const PLAYER_ZONE_MUTATOR = /\b(?:hand|library|battlefield|graveyard|exile|command|stack|history|pendingTriggers)\.(?:push|pop|shift|unshift|splice|sort|reverse)\s*\(/;

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.(?:js|jsx|mjs)$/.test(entry.name) ? [full] : [];
  });
}

function classify(rel) {
  if (rel === 'src/App.jsx' || rel.startsWith('src/components/') || rel.startsWith('src/utils/')) return 'UI/consumer';
  if (rel.startsWith('src/ai/')) return 'AI';
  if (/src\/engine\/(?:EffectEngine|TriggerEngine|StaticEngine|ReplacementEngine|TokenDefinitions)\.js$/.test(rel)) return 'card/mechanic engine';
  if (rel.startsWith('src/engine/')) return 'core engine';
  return 'other';
}

const entries = [];
for (const file of walk(SRC)) {
  const rel = path.relative(ROOT, file).replaceAll('\\', '/');
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, index) => {
    const category = classify(rel);
    const code = line.replace(/\/\/.*$/, '');
    if (![PROPERTY_ASSIGNMENT, INDEXED_ASSIGNMENT, ZONE_MUTATOR, PLAYER_ZONE_MUTATOR].some(re => re.test(code))) return;
    // Consumer snapshots and strategy-local structures are not authoritative.
    // Direct consumer access to engine.state is guarded separately by check-architecture.mjs.
    if ((category === 'UI/consumer' || category === 'AI') && !/\b(?:engine|this\.engine|e)\.state\b/.test(code)) return;
    entries.push({ file: rel, line: index + 1, category, code: line.trim() });
  });
}

const byCategory = entries.reduce((acc, item) => ((acc[item.category] ||= []).push(item), acc), {});
const outputDir = path.join(ROOT, 'docs', 'architecture');
fs.mkdirSync(outputDir, { recursive: true });
const jsonPath = path.join(outputDir, 'step1-mutation-inventory.json');
const mdPath = path.join(outputDir, 'step1-mutation-inventory.md');

fs.writeFileSync(jsonPath, JSON.stringify({ generatedAt: new Date().toISOString(), total: entries.length, entries }, null, 2) + '\n');
let md = '# Step 1 Mutation-Path Inventory\n\n';
md += 'Generated by `npm run audit:mutations`. It inventories direct writes to authoritative game-state fields and direct mutators on game zones/stack/history. Each path is tagged so later steps can migrate it without losing behavior.\n\n';
md += `**Total direct mutation paths found:** ${entries.length}\n\n`;
for (const category of ['UI/consumer', 'AI', 'card/mechanic engine', 'core engine', 'other']) {
  const rows = byCategory[category] || [];
  md += `## ${category} (${rows.length})\n\n`;
  if (!rows.length) { md += '- None.\n\n'; continue; }
  for (const item of rows) md += `- \`${item.file}:${item.line}\` — \`${item.code.replaceAll('`', '\\`')}\`\n`;
  md += '\n';
}
fs.writeFileSync(mdPath, md);
console.log(`Wrote ${entries.length} direct mutation paths to ${path.relative(ROOT, mdPath)} and JSON inventory.`);
